//结构体成员通常按最大成员对齐，最终大小是最大成员的倍数
struct arm64_decoded_instruction
{
    // 顶层指令大类；如 ADD X0,X1,X2 属于寄存器数据处理类。
    enum arm64_instruction_class
    {
        ARM64_INSTRUCTION_CLASS_UNKNOWN, // 无效/尚未分类，不是指令类别

        ARM64_INSTRUCTION_CLASS_SME, // SME 可伸缩矩阵扩展指令，当前仅识别编码空间
        ARM64_INSTRUCTION_CLASS_SVE, // SVE 可伸缩向量扩展指令，当前仅识别编码空间
        ARM64_INSTRUCTION_CLASS_LOAD_STORE,
        ARM64_INSTRUCTION_CLASS_DATA_PROCESSING_REGISTER,
        ARM64_INSTRUCTION_CLASS_DATA_PROCESSING_SIMD_FP,
        ARM64_INSTRUCTION_CLASS_DATA_PROCESSING_IMMEDIATE,
        ARM64_INSTRUCTION_CLASS_BRANCH_EXCEPTION_SYSTEM,
    } instruction_class;

    enum arm64_instruction instruction;

    /*
    以下成员是所有已支持编码形式可能使用的语义字段集合，不是固定数量的操作数槽。
    一条指令通常只填写其中少数字段；ARM64_DECODE_OK 时，由 instruction 决定哪些字段有效。
    */

    int64_t offset; // 已完成符号扩展和尺度换算的相对偏移；如 B label 或 ADR X0,label 的目标相对偏移，单位为字节。

    uint8_t condition; // 条件码；如 B.EQ label 或 CSEL X0,X1,X2,NE 中的 EQ/NE。
    uint8_t nzcv;      // 条件不满足时写入的 NZCV 值；如 CCMP X0,X1,#0xA,EQ 中的 #0xA。

    /*
    当前指令的立即数操作数或立即数载荷；具体位宽和表示形式由 instruction 决定。
    通常保存解码后的有效值；例如 ADD X0,X1,#0x12 保存 0x12，SVC #0x80 保存 0x80。
    AdvSIMD modified-immediate 指令中保存编码得到的 imm8，需结合 simd_cmode 和 element_width 解释。
    */
    uint64_t immediate;

    /*
    immr 和 imms 是 A64 位掩码编码中的两个 6 位字段，分别对应 R（旋转量）和 S。
    对 SBFM/BFM/UBFM，immr 是循环右移量；在不发生回绕的位域中，它对应位域起始位。
    imms 是参与生成位域掩码的结束位字段；在不发生回绕的位域中，它对应位域结束位。
    对 AND/ORR/EOR/ANDS 的逻辑立即数，二者与 N 一起确定重复元素和其中的位模式。
    例如 UBFM x0,x1,#8,#15 中 immr=8、imms=15，表示选取 x1[15:8]。
    */
    uint8_t immr;
    uint8_t imms;
    uint64_t bitfield_wmask; // SBFM/BFM/UBFM 的 DecodeBitMasks 写掩码 WMask。
    uint64_t bitfield_tmask; // SBFM/BFM/UBFM 的 DecodeBitMasks 顶部掩码 TMask。
    uint8_t simd_cmode;      // AdvSIMD modified-immediate 的原始 cmode[3:0] 编码；它决定 immediate 中 imm8 的元素宽度、移位或特殊扩展形式，不是独立的立即数。

    // 寄存器扩展、移位及其他操作数修饰。
    uint8_t extend_type;  // 扩展类型编码；如 ADD X0,X1,W2,UXTW #2 中的 UXTW。
    uint8_t shift_type;   // 移位类型编码；如 ADD X0,X1,X2,LSR #3 中的 LSR。
    uint8_t shift_amount; // 移位位数；如 ADD X0,X1,X2,LSL #3 中的 3，或 ADD X0,X1,#1,LSL #12 中的 12。

    // 系统寄存器由 op0、op1、CRn、CRm、op2 打包为 ARM64_SYSREG_KEY。
    uint16_t sysreg;

    // SIMD/FP 元素布局。宽度单位均为位，索引从 0 开始。
    uint8_t element_width; // 单个 SIMD/FP 元素的位宽；如 ADD V0.4S,V1.4S,V2.4S 中每个元素为 32 位。
    uint8_t lane_index;    // SIMD 元素的 lane 编号；如 UMOV W0,V1.S[2] 中的 lane_index=2。

    /*
    A64 编码图中的寄存器指定字段，均保存 5 位编号。
    它们不是固定的“第几个汇编操作数”；寄存器组及编号 31 的含义由 instruction 决定。
    */
    uint8_t rd;  // Rd 字段；如 ADD X0,X1,X2 中的目的寄存器 X0。
    uint8_t rn;  // Rn 字段；如 ADD X0,X1,X2 中的第一个源寄存器 X1。
    uint8_t rm;  // Rm 字段；如 ADD X0,X1,X2 中的第二个源寄存器 X2。
    uint8_t ra;  // Ra 字段；如 MADD X0,X1,X2,X3 中的加数寄存器 X3。
    uint8_t rt;  // Rt 字段；如 LDR X0,[X1] 中的加载目标寄存器 X0。
    uint8_t rt2; // Rt2 字段；如 LDP X0,X1,[X2] 中的第二个加载目标寄存器 X1。
    uint8_t rs;  // Rs 字段；如 STXR W0,X1,[X2] 中接收独占访问状态的 W0。

    // 指令整体处理或传输的位宽；如 ADD W0,W1,W2 为 32，ADD X0,X1,X2 为 64，ADD V0.4S,V1.4S,V2.4S 为 128。
    uint8_t operand_width;
};

/*
解码一条 AArch64 指令。

调用方提供最终结果存储地址，decoder 直接填充该对象，避免大结构体按值返回时
产生隐藏返回槽以及调用端的结构体复制。

返回值为 OK 时，instruction_class、instruction 和该指令对应的 operands 完整有效。
返回值不是 OK 时，decoded 整体无效并被置零；调用方不得依赖其中任何字段执行或重定位。
参数0:待解码的一条 32 位 A64 指令机器码
参数1:解码结果
*/
enum arm64_decode_status arm64_decode_instruction(uint32_t raw, struct arm64_decoded_instruction *decoded);

